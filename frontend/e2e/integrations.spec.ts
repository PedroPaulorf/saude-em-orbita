import { test, expect } from '@playwright/test'
import { exampleCsv, exampleFile } from '../src/lib/wearables'
import { login, logout } from './helpers'
test('AROW links and wearable imports work with consent, normalized formats, Apple XML, duplicates and private persistent history', async ({ page }) => {
  test.setTimeout(90_000)
  await page.route('**/DONKI-API/**', route => route.abort())
  await page.goto('/'); await login(page, 'crew02')
  await expect(page.getByRole('link', { name: 'Open NASA AROW information' })).toHaveAttribute('href', /www\.nasa\.gov\/missions\/artemis/)
  await page.getByRole('link', { name: 'Mission & device integrations', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Mission & device integrations' })).toBeVisible()
  await expect(page.getByText('0 imported samples saved for this account.')).toBeVisible()
  const file = page.getByLabel('Measurement file', { exact: true })
  const source = page.getByLabel('Data source', { exact: true })
  const save = page.getByRole('button', { name: 'Save imported measurements', exact: true })
  const consent = page.getByRole('checkbox', { name: /I reviewed the source/ })
  const postCount: string[] = []
  page.on('request', req => { if (req.method() === 'POST' && req.url().endsWith('/wearables/imports')) postCount.push(req.url()) })
  await source.selectOption('garmin')
  await file.setInputFiles({ name: 'garmin.csv', mimeType: 'text/csv', buffer: Buffer.from(exampleCsv('garmin')) })
  await expect(page.getByRole('heading', { name: 'Import preview', exact: true })).toBeVisible()
  await expect(save).toBeDisabled(); expect(postCount.length).toBe(0)
  await consent.check(); await save.click()
  await expect(page.getByText(/Import saved: 1 added, 0 duplicates/)).toBeVisible()
  await file.setInputFiles({ name: 'garmin.csv', mimeType: 'text/csv', buffer: Buffer.from(exampleCsv('garmin')) })
  await consent.check(); await save.click()
  await expect(page.getByText(/Import saved: 0 added, 1 duplicates/)).toBeVisible()
  await source.selectOption('samsung')
  await file.setInputFiles({ name: 'samsung.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(exampleFile('samsung'))) })
  await consent.check(); await save.click()
  await expect(page.getByText(/Import saved: 1 added, 0 duplicates/)).toBeVisible()
  await source.selectOption('actlumus')
  await file.setInputFiles({ name: 'actlumus.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(exampleFile('actlumus'))) })
  await consent.check(); await save.click()
  await expect(page.getByText(/Import saved: 1 added, 0 duplicates/)).toBeVisible()
  await expect(page.getByText('Photopic light: 120 lux', { exact: true })).toBeVisible()
  await source.selectOption('apple')
  const xml = '<?xml version="1.0"?><HealthData><Record type="HKQuantityTypeIdentifierOxygenSaturation" sourceName="Fixture Watch" unit="%" value="0.97" startDate="2026-11-14 09:00:00 -0300" endDate="2026-11-14 09:00:01 -0300"/><Record type="HKCategoryTypeIdentifierSleepAnalysis"/></HealthData>'
  await file.setInputFiles({ name: 'export.xml', mimeType: 'application/xml', buffer: Buffer.from(xml) })
  await expect(page.getByText(/1 unsupported XML records skipped/)).toBeVisible()
  await expect(page.getByText(/Oxygen saturation: 97 %/)).toBeVisible()
  await consent.check(); await save.click()
  await expect(page.getByText('4 imported samples saved for this account.')).toBeVisible()
  const before = postCount.length
  await file.setInputFiles({ name: 'unsafe.xml', mimeType: 'application/xml', buffer: Buffer.from('<!DOCTYPE HealthData SYSTEM "https://example.com/external"><HealthData/>') })
  await expect(page.getByRole('alert')).toContainText('external document types')
  expect(postCount.length).toBe(before)
  await page.reload()
  await expect(page.getByText('4 imported samples saved for this account.')).toBeVisible()
  const checkins = await page.request.get('http://127.0.0.1:3003/api/v1/me/checkins')
  expect((await checkins.json()).items).toHaveLength(0)
  await page.screenshot({ path: 'test-results/integrations-desktop.png', fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.screenshot({ path: 'test-results/integrations-mobile.png', fullPage: true })
  await logout(page)
  await login(page, 'crew03')
  await page.goto('/#/integrations')
  await expect(page.getByText('0 imported samples saved for this account.')).toBeVisible()
  await expect(page.getByText('Oxygen saturation: 97 %', { exact: true })).toHaveCount(0)
})
