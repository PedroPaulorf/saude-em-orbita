import { test, expect, type Page } from '@playwright/test'
test.use({ actionTimeout: 15_000 })

async function login(page: Page, username: string) {
  await page.getByLabel('Username', { exact: true }).fill(username)
  await page.getByLabel('Password', { exact: true }).fill('browser-fixture-password-29')
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Log out', exact: true })).toBeVisible()
}
test('female calendar creates, persists, edits and deletes private records on desktop and mobile', async ({ page }) => {
  test.setTimeout(90_000)
  await page.route('**/DONKI-API/**', route => route.abort())
  await page.goto('/'); await login(page, 'crew03')
  await page.getByRole('link', { name: /Menstrual calendar Record period/ }).click()
  await expect(page.getByRole('heading', { name: 'Menstrual calendar', exact: true })).toBeVisible()
  await expect(page.getByText('No periods recorded in this month.')).toBeVisible()
  await page.getByLabel('Go to month', { exact: true }).fill('2024-02')
  await expect(page.getByRole('heading', { name: 'February 2024' })).toBeVisible()
  await page.getByRole('button', { name: '28 Feb 2024', exact: true }).click()
  await page.getByLabel('End date', { exact: false }).fill('2024-03-02')
  await page.getByLabel('Flow', { exact: true }).selectOption('moderate')
  await page.getByLabel('Pain (0–10, optional)', { exact: true }).fill('0')
  await page.getByLabel('Cramps', { exact: true }).check()
  await page.getByLabel('Notes (optional)', { exact: true }).fill('Fictional browser record')
  await page.getByRole('button', { name: 'Save period', exact: true }).click()
  await expect(page.getByText('Period saved to your account.')).toBeVisible()
  await expect(page.getByRole('button', { name: '29 Feb 2024, recorded period', exact: true })).toBeVisible()
  await expect(page.getByText('4 days · Flow: Moderate · Pain: 0/10')).toBeVisible()
  await page.reload()
  // The page reopens at the current month. Selecting the original month reloads the saved record.
  await page.getByLabel('Go to month', { exact: true }).fill('2024-03')
  await expect(page.getByRole('button', { name: '1 Mar 2024, recorded period', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Edit period starting 28 Feb 2024', exact: true }).click()
  await page.getByLabel('Flow', { exact: true }).selectOption('light')
  await page.getByRole('button', { name: 'Save period', exact: true }).click()
  await expect(page.getByText('4 days · Flow: Light · Pain: 0/10')).toBeVisible()
  await page.screenshot({ path: 'test-results/menstrual-desktop.png', fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  await page.getByRole('button', { name: 'Edit period starting 28 Feb 2024', exact: true }).click()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.evaluate(() => window.scrollTo(0, 0))
  await page.screenshot({ path: 'test-results/menstrual-mobile.png', fullPage: true })
  await page.getByRole('button', { name: 'Cancel', exact: true }).click()
  await page.getByRole('button', { name: 'Delete period starting 28 Feb 2024', exact: true }).click()
  await page.getByRole('button', { name: 'Confirm delete', exact: true }).click()
  await expect(page.getByText('No periods recorded in this month.')).toBeVisible()
  await page.getByRole('button', { name: 'Log out', exact: true }).click()
  await login(page, 'crew02')
  await expect(page.getByRole('link', { name: /Menstrual calendar Record period/ })).toHaveCount(0)
  await page.goto('/#/menstrual')
  await expect(page.getByText('This calendar is available in the female profile.')).toBeVisible()
  const denied = await page.request.get('http://127.0.0.1:3003/api/v1/me/menstrual?from=2024-01-01&to=2024-12-31')
  expect(denied.status()).toBe(403)
})
