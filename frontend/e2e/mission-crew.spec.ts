import { test, expect } from '@playwright/test'
import { login, logout } from './helpers'

test('demo login, missions, crew and prevention points coexist with the calendar and integrations', async ({ page }) => {
  test.setTimeout(90_000)
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.route('**/DONKI-API/**', route => route.abort())
  await page.goto('/#/login')
  await page.locator('[data-profile="crew03"]').click()
  await expect(page.getByLabel('Password', { exact: true })).toHaveValue(process.env.VITE_DEMO_PASSWORD || 'senha123')
  await page.keyboard.press('Enter')
  await expect(page.getByRole('heading', { name: 'Choose your mission', exact: true })).toBeVisible()
  await page.getByRole('button', { name: /^Choose Mars:/ }).click()
  const mission = page.getByRole('link', { name: 'Mars Day 47', exact: true })
  await expect(mission).toBeVisible()
  const crew = page.getByRole('region', { name: 'Crew', exact: true })
  await expect(crew).toBeVisible()
  await expect(crew.getByRole('listitem')).toHaveCount(2)
  await page.reload()
  await expect(mission).toBeVisible()
  // Both routes from the formerly conflicting lists must remain reachable.
  await page.goto('/#/menstrual')
  await expect(page.getByRole('heading', { name: 'Menstrual calendar', exact: true })).toBeVisible()
  await page.goto('/#/integrations')
  await expect(page.getByRole('heading', { name: 'Mission & device integrations', exact: true })).toBeVisible()
  await page.goto('/#/check/health')
  await expect(crew).toHaveCount(0)
  await page.goto('/#/prevention')
  const objectives = page.getByRole('region', { name: "Today's objectives", exact: true })
  const first = objectives.getByRole('checkbox').first()
  await expect(first).toHaveAttribute('aria-checked', 'false')
  await first.click()
  await expect(objectives.getByRole('status')).toContainText('15 points')
  await page.reload()
  await expect(first).toHaveAttribute('aria-checked', 'true')
  await expect(objectives.getByRole('status')).toContainText('15 points')
  await first.click()
  await expect(objectives.getByRole('status')).toContainText('0 points')
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: 'test-results/mission-crew-prevention-mobile.png', fullPage: true })
  await logout(page)
  await login(page, 'crew02')
  // The second account starts with its own mission, rather than inheriting Mars.
  await page.goto('/#/mission')
  await expect(page.getByRole('button', { name: /^Choose ISS:/ })).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('button', { name: /^Choose Moon:/ }).click()
  await page.goto('/#/prevention')
  await expect(objectives.getByRole('checkbox').first()).toHaveAttribute('aria-checked', 'false')
  await logout(page)
  await login(page, 'crew03')
  await page.goto('/#/mission')
  await expect(page.getByRole('button', { name: /^Choose Mars:/ })).toHaveAttribute('aria-pressed', 'true')
  expect(errors).toEqual([])
})
